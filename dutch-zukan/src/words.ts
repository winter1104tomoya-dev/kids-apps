export type Shape = 'circle' | 'square' | 'triangle' | 'heart' | 'star' | 'rectangle' | 'diamond';

export interface Word {
  pic: string;
  /** src/img にある絵の名前（拡張子なし）。あれば絵文字の代わりに使う */
  img?: string;
  nl: string;
  art?: 'de' | 'het';
  ja: string;
  /** 日本語を読み上げるときの書き方（漢字にすると、読み上げのアクセントが正しくなりやすい）。なければ ja */
  say?: string;
  /** 色カテゴリ用：絵文字の代わりに塗る色 */
  color?: string;
  /** 数字カテゴリ用：絵文字の代わりに数字と同じ数の丸を出す */
  num?: number;
  /** かたちカテゴリ用：絵文字の代わりに描く図形 */
  shape?: Shape;
}

